def send_to_discord(alert_data, vt_data, ai_analysis):
    """Send formatted alert to Discord webhook"""

    # Color mapping based on severity
    color_map = {
        "Critical": 16711680,  # Red
        "High": 16753920,       # Orange
        "Medium": 16776960,     # Yellow
        "Low": 65280,           # Green
        "Error": 8421504,       # Gray
        "Unknown": 8421504      # Gray
    }

    severity = ai_analysis.get('severity', 'Unknown')
    color = color_map.get(severity, 16711680)

    # Build VT summary text
    if vt_data.get('vt_available'):
        vt_text = f"VT: {vt_data.get('malicious', 0)} malicious, {vt_data.get('suspicious', 0)} suspicious"
    else:
        vt_text = "VT: No data available"

    # Create Discord embed
    payload = {
        "embeds": [{
            "title": " SentinelFlow Alert",
            "color": color,
            "fields": [
                {
                    "name": "Alert ID",
                    "value": alert_data['alertId'],
                    "inline": True
                },
                {
                    "name": "Domain",
                    "value": alert_data['dstDomain'],
                    "inline": True
                },
                {
                    "name": "Severity",
                    "value": severity,
                    "inline": True
                },
                {
                    "name": "Threat Intelligence",
                    "value": vt_text,
                    "inline": False
                },
                {
                    "name": "Reason",
                    "value": ai_analysis.get('reason', 'No analysis available'),
                    "inline": False
                }
            ],
            "timestamp": datetime.now().isoformat(),
            "footer": {
                "text": "SentinelFlow Security Automation"
            }
        }]
    }

    try:
        response = requests.post(DISCORD_WEBHOOK_URL, json=payload)
        if response.status_code == 204:
            print("   Alert sent to Discord successfully!")
            return True
        else:
            print(f"   Discord webhook error: {response.status_code}")
            return False
    except Exception as e:
        print(f"   Discord error: {str(e)}")
        return False

