def analyze_with_groq(alert_data, vt_data):
    """Send enriched alert to Groq API for severity analysis"""

    url = "https://api.groq.com/openai/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {GROQ_API_KEY}",
        "Content-Type": "application/json"
    }

    # Construct prompt with alert and VT data
    vt_info = f"VT Scan: {vt_data.get('reputation', 'Unknown')} with {vt_data.get('malicious', 0)} malicious detections" if vt_data.get('vt_available') else "VT Scan: No threat intelligence available"

    prompt = f"""You are a security analyst. Analyze this security alert and return ONLY valid JSON.

Alert ID: {alert_data['alertId']}
Domain: {alert_data['dstDomain']}
{vt_info}

Return JSON in this exact format:
{{
  "severity": "Critical" or "High" or "Medium" or "Low",
  "reason": "Brief explanation of the threat (1 sentence)"
}}

Severity guidelines:
- Critical: Immediate threat, active exploitation likely
- High: Serious vulnerability, should be prioritized
- Medium: Potential threat, needs investigation
- Low: Informational, minimal risk
"""

    payload = {
        "model": "llama-3.1-8b-instant",
        "messages": [
            {"role": "system", "content": "You are a security analyst. Always return valid JSON."},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.1,
        "response_format": {"type": "json_object"}
    }

    try:
        response = requests.post(url, headers=headers, json=payload)
        if response.status_code == 200:
            result = response.json()
            ai_content = result['choices'][0]['message']['content']

            # Parse JSON from AI response
            try:
                # Handle case where AI returns string that needs parsing
                if isinstance(ai_content, str):
                    analysis = json.loads(ai_content)
                else:
                    analysis = ai_content

                print(f"  → AI Analysis: Severity={analysis.get('severity', 'Unknown')}")
                print(f"  → Reason: {analysis.get('reason', 'No reason provided')}")
                return analysis
            except json.JSONDecodeError:
                print(f"   Failed to parse AI response as JSON")
                print(f"  Raw response: {ai_content[:100]}...")
                # Fallback
                return {
                    "severity": "Unknown",
                    "reason": "AI response parsing failed"
                }
        else:
            print(f"   Groq API error: {response.status_code}")
            return {"severity": "Error", "reason": f"API error: {response.status_code}"}
    except Exception as e:
        print(f"   Groq API exception: {str(e)}")
        return {"severity": "Error", "reason": f"Exception: {str(e)}"}

