def enrich_with_virustotal(domain):
    """Query VirusTotal API for domain reputation"""
    url = f"https://www.virustotal.com/api/v3/domains/{domain}"
    headers = {"x-apikey": VT_API_KEY}

    try:
        response = requests.get(url, headers=headers)
        if response.status_code == 200:
            data = response.json()
            # Extract relevant threat intelligence
            stats = data.get("data", {}).get("attributes", {}).get("last_analysis_stats", {})
            malicious = stats.get("malicious", 0)
            suspicious = stats.get("suspicious", 0)
            harmless = stats.get("harmless", 0)

            vt_summary = {
                "vt_available": True,
                "malicious": malicious,
                "suspicious": suspicious,
                "harmless": harmless,
                "total_scans": malicious + suspicious + harmless,
                "reputation": "SUSPICIOUS" if malicious > 0 or suspicious > 0 else "CLEAN"
            }
            print(f"  → VirusTotal: {malicious} malicious, {suspicious} suspicious detections")
            return vt_summary
        else:
            print(f"   VirusTotal: Domain not found or API error")
            return {"vt_available": False, "error": "Domain not found"}
    except Exception as e:
        print(f"   VirusTotal API error: {str(e)}")
        return {"vt_available": False, "error": str(e)}

